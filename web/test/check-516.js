// app-5.16 checks: curve TARGET, +10s landing tag, dock backdrop, rig settings, lifetime stats.
// usage: node test/check-516.js <rootdir> <outdir>
const { chromium } = require('playwright');
const path = require('path');
const [,, root, out] = process.argv;
let bad = 0;
const check = (name, ok, detail = '') => { if (!ok) bad++; console.log(`CHECK ${ok ? 'ok  ' : 'FAIL'} ${name}${detail ? ' :: ' + detail : ''}`); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  p.on('pageerror', e => { bad++; console.log('PAGEERROR', e.message); });
  await p.addInitScript({ path: path.join(__dirname, 'fakebt.js') });
  await p.addInitScript(() => { for (const [k, v] of Object.entries({ age21: 'yes', fsTip: 'done', tutorialSeen: 'yes' })) localStorage.setItem('torchless.' + k, v); });
  await p.goto('file://' + path.resolve(root) + '/index.html');
  await p.waitForTimeout(700);
  const text = s => p.evaluate(s => document.querySelector(s)?.textContent ?? '', s);
  const vis = s => p.evaluate(s => { const e = document.querySelector(s); if (!e) return false; const r = e.getBoundingClientRect(); return r.width > 0 && r.height > 0; }, s);
  await p.click('#linkIt'); await p.waitForTimeout(2500);
  await p.evaluate(() => document.querySelector('.tut')?.remove());
  await p.click('#p5'); await p.waitForTimeout(1200);
  check('idle curve preset: TARGET shows the range', (await text('#cTarget')) === '435–523°', await text('#cTarget'));
  await p.click('#heat'); await p.waitForTimeout(1200);
  check('heating up: TARGET is the start temp', (await text('#cTarget')) === '435°', await text('#cTarget'));
  check('heating: preset keys folded away', !(await vis('#p1')) && !(await vis('#planBtn')));
  await p.waitForTimeout(9000);
  const t1 = await text('#cTarget');
  check('mid-curve: TARGET climbs', Number(t1.replace('°', '')) > 450, t1);
  check('+10s tag says where it lands', /^TO ~5\d\d°$/.test(await text('#extend .tag')), await text('#extend .tag'));
  await p.screenshot({ path: `${out}/a-heating-curve.png` });
  await p.click('#extend'); await p.waitForTimeout(1500);
  check('+10s tag moves on after a tap', /^TO ~5\d\d°$/.test(await text('#extend .tag')), await text('#extend .tag'));
  for (let i = 0; i < 4; i++) { await p.click('#extend'); await p.waitForTimeout(1300); }
  check('+10s never shows past the rig top', /^TO (~[56]\d\d°|650° MAX)$/.test(await text('#extend .tag')) && !/6[5-9]\d|7\d\d/.test((await text('#extend .tag')).replace('650° MAX', '')), await text('#extend .tag'));
  await p.waitForTimeout(3000); await p.click('#cut'); await p.waitForTimeout(1500);
  check('after CUT: presets back', await vis('#p1'));
  await p.click('nav [data-tab=rig]'); await p.waitForTimeout(500);
  await p.screenshot({ path: `${out}/b-rig.png`, fullPage: true });
  await p.click('text=Rig settings'); await p.waitForTimeout(800);
  await p.screenshot({ path: `${out}/c-settings.png`, fullPage: true });
  const log = () => p.evaluate(() => window.__rig.log.slice());
  let before = (await log()).length;
  await p.click('.page >> text=Stealth'); await p.waitForTimeout(900);
  check('stealth sends brightness 0', (await log()).slice(before).some(l => /^RX 185,/.test(l) && l.split(',')[13] === '0'));
  await p.selectOption('.page select', '30'); await p.waitForTimeout(700);
  check('auto shut-off 30 min sent', (await log()).some(l => /^RX 185,/.test(l) && l.split(',')[8] === '30'));
  await p.click('.page .seg >> text=°C'); await p.waitForTimeout(900);
  check('units C sent', (await log()).some(l => /^RX 185,/.test(l) && l.split(',')[9] === '12'));
  await p.click('.page .seg >> text=°F'); await p.waitForTimeout(900);
  await p.click('text=START CLEANING ASSIST'); await p.waitForTimeout(1600);
  check('cleaning assist start sent', (await log()).includes('RX 198,4,170,198'));
  check('cleaning assist shows countdown', /Warming/.test(await p.evaluate(() => document.querySelector('.page').textContent)));
  await p.screenshot({ path: `${out}/d-settings-clean.png`, fullPage: true });
  await p.click('.page >> text=CANCEL'); await p.waitForTimeout(800);
  check('cleaning assist cancel sent', (await log()).includes('RX 198,4,0,198'));
  check('no heat start from settings', !(await log()).slice(before).some(l => /^RX 185,/.test(l) && l.split(',')[10] === '170'));
  await p.click('.page .textBtn'); await p.waitForTimeout(400);
  await p.click('text=Lifetime stats'); await p.waitForTimeout(1200);
  const pg = await p.evaluate(() => document.querySelector('.page').textContent);
  check('lifetime: rig heat cycles 399', /Heat cycles399/.test(pg));
  check('lifetime: Torchless dabs counted', /Dabs1/.test(pg), pg.slice(0, 300));
  check('lifetime: stats were requested', (await log()).includes('RX 178,4,255,178'));
  await p.screenshot({ path: `${out}/e-lifetime.png`, fullPage: true });
  await b.close();
  console.log(bad ? `DONE with ${bad} problem(s)` : 'DONE clean');
  process.exit(bad ? 1 : 0);
})();
